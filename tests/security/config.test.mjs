// The single source of truth, config/veloxfetch.yaml, and the files generated from it are in step, and the
// project's trust anchors (update repository, extension ids) are compiled in — never read from disk at run time.
// Run: node --test tests/security/*.test.mjs
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), "utf8");

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["target", "node_modules", "dist", ".git"].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

test("the generated config files and the install scripts are in step with config/veloxfetch.yaml", () => {
  // The generator's own --check: regenerates in memory and compares to disk, non-zero (and a message) on drift.
  execFileSync("node", ["scripts/gen-config.mjs", "--check"], { cwd: ROOT, stdio: "pipe" });
});

test("the single source of truth pins the public download repository and a valid store id", () => {
  const yaml = read("config", "veloxfetch.yaml");
  const val = (k) => new RegExp(`^${k}:\\s*(.+?)\\s*$`, "m").exec(yaml)?.[1];
  assert.equal(val("releases_owner"), "IlyesBs");
  assert.equal(val("releases_repo"), "VeloxFetch-releases");
  assert.match(val("chrome_store_id"), /^[a-p]{32}$/, "the Chrome Web Store id is 32 chars a–p");
  assert.equal(val("native_host_name"), "app.velox.fetch");
  // The Firefox Add-ons listing the app opens for Firefox users: an https addons.mozilla.org page, generated
  // into the desktop binary as FIREFOX_STORE_URL.
  const firefoxStore = val("firefox_store_url");
  assert.match(firefoxStore, /^https:\/\/addons\.mozilla\.org\/[^\s]+$/, "firefox_store_url is an https addons.mozilla.org page");
  assert.match(
    read("apps", "desktop", "src-tauri", "src", "generated", "identity.rs"),
    new RegExp(`FIREFOX_STORE_URL: Option<&str> = Some\\("${firefoxStore.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}"\\)`),
    "FIREFOX_STORE_URL is generated from the YAML",
  );
});

test("the trust anchors are compiled in, never read from a file at run time", () => {
  // No shipped source names the config file: the values reach the binary only through the generated constants,
  // so an install on an unknown computer cannot be pointed at another update server or made to trust an extension.
  const namesYamlInCode = (src) =>
    src.split(/\r?\n/).some((line) => line.replace(/\/\/.*$/, "").includes("veloxfetch.yaml"));
  const offenders = [...walk(path.join(ROOT, "crates")), ...walk(path.join(ROOT, "apps"))]
    .filter((f) => f.endsWith(".rs"))
    .filter((f) => namesYamlInCode(fs.readFileSync(f, "utf8")))
    .map((f) => path.relative(ROOT, f));
  assert.deepEqual(offenders, [], "no shipped Rust should read config/veloxfetch.yaml at run time");

  // Each generated file carries the @generated banner, so it is not hand-edited.
  for (const g of [
    "crates/browser-bridge/src/generated/identity.rs",
    "crates/system-integration/src/generated/identity.rs",
    "apps/desktop/src-tauri/src/generated/identity.rs",
  ]) {
    assert.match(read(g), /^\/\/ @generated by scripts\/gen-config\.mjs/, `${g} is generated`);
  }
});
